import { useLayoutEffect } from 'react'

/**
 * その画面を開いたとき、ページのいちばん上を見せる（2026-08-21 便IU・④）。
 *
 * オーナー原文（不具合の報告）:
 *   「・「別の週から入れる」押下後ページの真ん中にスクロールしてしまう。」
 *
 * 【本当の原因】このアプリは1枚のページの中で画面を差し替える作り（HashRouter）で、
 * **画面が変わってもブラウザの縦位置はそのまま残る**。押した「別の週から入れる」は
 * 「週」の画面のいちばん下にあるので、押した時点の縦位置は1000pxを超えている。
 * 着いた先のページはそこまで長くないため、縦位置がそのページの最大値まで詰められて
 * **ちょうど真ん中あたり**で止まっていた（390×844の実測で 1145px → 217px）。
 * 押した先のコードが動かしていたのではなく、**先頭へ戻す1行が無かった**のがこの症状。
 *
 * 2026-08-17 にオーナーが「ページ開いた時に、基本的にページのいちばん上を表示して」と
 * 言ったときは献立タブだけを直したので、あとから増えた画面が同じ穴に落ちた。
 * 同じことを画面ごとに書き写すとまた落ちるので、ここ1本にまとめる。
 *
 * **描画前（useLayoutEffect）に動かす**＝出てから動くと、一瞬だけ途中が見えてちらつく。
 *
 * 覚えていた位置へ戻したい画面（並行調理ナビ・献立の週）はこれを使わない。
 * どちらでもよい画面は無い＝**開いたときの縦位置は必ずどちらかを選ぶ**。
 * 見張りは scripts/test-logic.mjs の IU-6。
 *
 * @param key 変わったらもう一度いちばん上へ戻すもの（レシピ詳細のidなど）。省略すると開いた1回だけ
 */
export function useScrollTopOnOpen(key?: string | number) {
  useLayoutEffect(() => {
    window.scrollTo(0, 0)
  }, [key])
}
