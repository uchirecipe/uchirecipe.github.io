import { toIngredientKey } from './kana'

/**
 * 「少々」「適量」のように分量が数値で書かれていない材料について、
 * 栄養価と原価が共通で参照する「仮の量」の一本化モジュール（2026-07-28 便BY/XREF-01）。
 *
 * 【なぜ1箇所に集めるか】従来は栄養側(nutrition.ts の matchAssumed)だけが仮の量を持ち、
 * 原価側(priceEstimate.ts)は「読めない分量＝マスタ金額をそのまま1行分」というだけの
 * フォールバックだった。その結果、同じ「ごま油 少々」が同じ画面で
 * 栄養＝計算対象外・原価＝1,200円（1Lボトル1本分）という食い違いを起こしていた。
 * 仮の量の置き場所を1つにして、どちらの数字も同じ前提から出るようにする。
 *
 * 【2つの表が別々の値なのは意図的】答えている問いが違う。
 * - ASSUMED_GRAMS_PER_SERVING: 「1食で“食べる”のは何gか」（栄養）
 * - TYPICAL_AMOUNTS: 「1回の調理で“使う”のはどれだけか」（原価。人数では増減しない）
 * 例えば炒め油は、鍋にひく量はレシピの人数が2人でも3人でも大きく変わらない一方、
 * 食べる量は1人あたりで数える。同じ数字にすると必ずどちらかが不自然になる。
 */

/**
 * 油の名寄せ判定。toIngredientKey 適用後の文字列と比較するため、カタカナ由来の語は
 * ひらがな化した形（「サラダ」→「さらだ」「オリーブ」→「おりーぶ」）で書く。
 * 「ごま油」「胡麻油」「揚げ油」は読み仮名辞書(ingredientReadings)で丸ごと
 * 「ごまあぶら」「あげあぶら」に変換されるため、その変換後の形も含める。
 */
export const OIL_NAMES = /(さらだ油|ごま油|ごまあぶら|あげあぶら|おりーぶおいる|おりーぶ油|^油$)/

/** 「少々」「適量」を仮の目安量で栄養計算に含めたときの結果 */
export interface AssumedGrams {
  /** 1食(1人分)あたりの仮の重量(g) */
  gramsPerServing: number
  /** UIに必ず出す仮定の説明（例: '少々 → 約0.5g/食'） */
  note: string
}

/**
 * 栄養計算用の「少々」「適量」の仮の目安量(1食あたりg・概算)。
 * 塩系はmemoの「約◯g」表記があればそれを優先。お好みで表記は食べるか不明なため対象外のまま。
 *
 * 判定はtoIngredientKey済みの表記(toHiragana適用後)で行う(2026-07-21・オーナー実機報告
 * 「対象外13件」調査で発見・修正)。旧実装は生の文字列(name)をそのまま比較しており、
 * 「黒胡椒」のような漢字・「コショウ」のようなカタカナ表記だとmatchNutritionFoodでは
 * 食品が見つかっているのに少々の仮定だけ効かない、という表記ゆれバグがあった。
 *
 * 油の3g/食は、文部科学省「日本食品標準成分表(八訂)増補2023年」の素揚げ実測
 * （じゃがいも02017→02067で吸油3.8%・にんじん06214→06346で2.2%）と整合する量。
 * 2026-07-28の裏取りで再確認したため値は据え置く。
 */
export function matchAssumedGrams(ing: {
  name: string
  amount?: string
  memo?: string
}): AssumedGrams | null {
  const name = ing.name
  const amount = ing.amount ?? ''
  const key = toIngredientKey(name)
  if (/お好みで/.test(name) || /お好みで/.test(amount)) return null
  if (/少々/.test(amount)) {
    // toIngredientKey適用後は「塩」は辞書(ingredientReadings)で必ず「しお」に変換されるため、
    // 判定は「しお」のみで足りる(「塩」がそのまま残るケースは無い)
    if (key.includes('しお')) {
      const m = (ing.memo ?? '').match(/約([\d.]+)g/)
      const g = m ? Number(m[1]) : 0.5
      return { gramsPerServing: g, note: `少々 → 約${g}g/食` }
    }
    if (key.includes('こしょう')) {
      return { gramsPerServing: 0.3, note: '少々 → 約0.3g/食' }
    }
  }
  if (/適量/.test(amount) && OIL_NAMES.test(key)) {
    return { gramsPerServing: 3, note: '適量 → 約3g/食(大さじ1/2を2食で使う想定)' }
  }
  return null
}

/**
 * 原価計算用の「1回の調理で使う量」(2026-07-28 便BY/COST-01)。
 *
 * 分量が数値で書かれていない材料は、従来マスタの登録単位1つ分の金額がそのまま1行に乗っていた。
 * 登録単位が販売単位（サラダ油400円/1L・ごま油1200円/1L・オリーブオイル1400円/1L。
 * docs/49の実売価格改定でこの単位になった）の食材では、「適量」1行にボトル1本分の金額が
 * 出るという桁違いの過大計上になる。ここに1回使用量を持つ食材だけ、その量で按分する。
 *
 * 【値の根拠】同梱の基本レシピ103品が、同じ食材の分量を数値で書いているときの最頻値。
 * 新しい相場・係数を発明せず、アプリ自身が持っているレシピの書き方をそのまま使う。
 * - サラダ油: 大さじ1(4件) / 小さじ1(2件) → 大さじ1
 * - ごま油: 小さじ1(12件) / 大さじ1(8件) / 小さじ2(1件) / 小さじ1/2(1件) → 小さじ1
 * - オリーブオイル: 大さじ1(4件) / 大さじ3・大さじ2・大さじ1/2(各1件) → 大さじ1
 *
 * 【載せない食材】小ねぎ・かつお節・白いりごま等の薬味は、登録単位が販売単位ではなく
 * 「1回のレシピで使う現実的な量」の小さめの目安で登録されており（docs/49 §7でオーナー了承済み）、
 * 満額でも1食分として過大にならない。既決事項なのでここでは触らない。
 */
const TYPICAL_AMOUNT_SOURCE: [name: string, amount: string][] = [
  ['サラダ油', '大さじ1'],
  ['ごま油', '小さじ1'],
  ['オリーブオイル', '大さじ1'],
  // 2026-08-22 便JG（オーナー原文「ハヤシライス・塩コショウサラダ油は分量なし。
  // こしょう５円…って高い」）。こしょうは登録単位が「小さじ1」なので、分量が書かれていない行に
  // **小さじ1杯まるごと(10円)** が乗っていた（2人分のレシピで1食5円）。
  // 【値の根拠】同梱109品でこしょうが数値で書かれたことは一度も無く（7件すべて「少々」）、
  // 最頻値が取れない。そこで**アプリ自身が栄養で使っている「少々」の量**をそのまま使う
  // （matchAssumedGrams のこしょう 0.3g・上の表と同じ出どころ）。
  // 成分表のこしょう 小さじ1=2g なので 10円×0.3/2＝1.5円→約2円になる。
  // 栄養と原価が同じ「少々」の量を見る、というこのモジュールの目的そのもの
  ['こしょう', '0.3g'],
  ['黒こしょう', '0.3g'],
  // 版9までの項目名。既存端末の行が改名前のまま残っていても同じ量が当たるようにしておく
  ['粗びき黒こしょう', '0.3g'],
]

const TYPICAL_AMOUNTS = new Map(
  TYPICAL_AMOUNT_SOURCE.map(([name, amount]) => [toIngredientKey(name), amount]),
)

/**
 * 食材名から「1回の調理で使う量」の文字列（例: '大さじ1'）を引く。
 * 持っていない食材は undefined（＝呼び出し側は従来どおりの扱いに戻る・後方互換）。
 */
export function typicalAmountFor(name: string): string | undefined {
  return TYPICAL_AMOUNTS.get(toIngredientKey(name))
}
