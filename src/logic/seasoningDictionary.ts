/** 薬味・香辛料か（末尾一致つき。「Ｓ＆Ｂ おろしにんにく」「粗びき唐辛子」も拾う） */
export function isGarnishOrSpiceName(name: string): boolean {
  const normalized = normalizeName(name)
  if (GARNISH_AND_SPICE_NAMES.has(normalized)) return true
  return [...GARNISH_AND_SPICE_NAMES].some((word) => word.length >= 2 && normalized.endsWith(word))
}

/**
 * 分量に「お好みで」を含む材料は主要食材から外す（例:「お好みで」「少々(お好みで)」）。
 * 数値が混ざっていて isSeasoningLike の非数値判定をすり抜けるケース
 * （例:「1(お好みで)」）もここで拾う。
 */
export function isOptionalAmount(amount: string): boolean {
  return amount.includes('お好みで')
}
