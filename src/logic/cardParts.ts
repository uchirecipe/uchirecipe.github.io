/**
 * レシピカードが「載せられる情報」の一覧と、**どの場所で何を載せるか**の表
 * （2026-08-19 便HY・オーナー承認済み）。
 *
 * オーナー原文:
 *   「レシピカードはフォーマットが揃っていれば、それぞれの場所で不要な情報はなくして
 *     シンプルにしたいのですが、どうでしょう？『今日なに作る？』だったら『基本レシピ』と
 *     食材表記はいらないように感じました。」
 *
 * 便HN（密度＝大／標準／小の3つ）と便HW（自前のカードを全部その3つに寄せた）で
 * **形**はそろった。そのとき、そろえるために「もともと出していなかった情報」まで
 * 一緒に付いてきた場所がある（「今日なに作る？」の候補に「基本レシピ」のバッジと
 * 主要食材のチップが増えたのがそれ）。この表は、そこから先の**引き算**を受け持つ。
 *
 * 決めごと（司令部裁定）:
 *  ① **骨格は動かさない**。絵の位置・料理名の位置・行の並び・字の大きさは全場所で同じ。
 *     切り替えるのは「載せるか載せないか」だけで、位置や大きさは切り替えない
 *  ② **足すのは共通部品を通す**。載せられるのは下の CARD_PART_KEYS に並んでいるものだけで、
 *     場所ごとに新しい項目をその場で足すことはできない（型でも見張りでも塞いである）
 *  ③ **どこで何を出すかは、この1か所だけに書く**。カード部品はここを読んで描き、
 *     scripts/test-logic.mjs の HY-1〜HY-4 が「表の外で描いていないか」を機械で見張る
 *
 * 逆に、**その場所ならではの短い情報と操作**（記録の日付・献立の役割・「作った！」ボタン・
 * 「選択中」の印など）は、この表ではなくカード部品の口（titleBadges / meta / infoLine /
 * actions）が受け持つ。あれは「レシピの属性」ではなく「その画面が持っている事情」で、
 * 場所ごとに違うのが当たり前のものなので、同じ物差しに載せない。
 */

/**
 * 共通カードが用意している「載せられる情報」。**ここに無いものは載せられない**。
 *
 *  time        … 調理時間（時計の絵＋◯分。「時短」絞り込み中は時短の時間に切り替わる）
 *  effort      … 手間（かんたん／ふつう／じっくり）
 *  season      … 季節（春・夏・秋・冬。「通年」は元から出さない）
 *  starter     … 「基本レシピ」（同梱レシピの見分け）
 *  ingredients … 主要食材のチップ（先頭3件まで）
 *  matchReason … 検索で当たった先（「タグ: 魚」「手順: 魚焼きグリル」。2026-08-20 便IH・②）
 *
 * matchReason だけは「レシピの属性」ではなく**探し方に対する答え**なので、出す言葉は
 * 呼び出し側（レシピ一覧）が組み立てて渡す。それでもこの表に載せてあるのは、
 * **出す場所を1か所で決めるため**——献立の枠のレシピ選びにも検索まどがあり、
 * 表に無ければ「渡せばどこでも出る」状態になる。渡せるのは表に載っている場所だけ、にしておく。
 *
 * NG食材の警告・「今日の献立」の印・栄養価の値は、この表では切らない。
 * どれも**呼び出し側が渡した材料があるときだけ**出る（ngIngredients / inTodayList /
 * nutrientBadgeText）ので、出す・出さないの判断はすでに呼び出し側が持っている。
 * とくにNG食材の警告は安全に関わるので、場所ごとに削れる列には置かない。
 */
export const CARD_PART_KEYS = [
  'time',
  'effort',
  'season',
  'starter',
  'ingredients',
  'matchReason',
] as const

export type CardPartKey = (typeof CARD_PART_KEYS)[number]

/**
 * カードを出す場所。**役目で分ける**（画面の名前では分けない）＝同じ役目の場所が
 * 増えても、新しい行を足さずに同じ名前を渡せばそろう。
 *
 *  recipeList   … レシピを並べて眺める／探す一覧（レシピ一覧のグリッド・一覧表示）。**省略時の既定**
 *  recipePicker … レシピを1品選ぶ一覧（献立の枠のレシピ選び・献立テンプレの差し替え・
 *                 買い物メモのレシピ選び）
 *  todayPlan    … 献立の「日」の「今日の献立」に並ぶ1品
 *  todaySuggest … 「今日なに作る？」が出す候補（1品／おまかせで組んだ主菜・副菜）
 *  cookedLog    … 作った記録（「最近作ったもの」・「作った記録の一覧」）
 *  planSlot     … 献立の枠に収まった1品（週・月・月の日の窓・献立テンプレの中身・
 *                 買い物メモの出所）
 */
export const CARD_PLACE_PARTS = {
  /**
   * レシピ一覧は**全部載せる**。ここは「どれにするか決める」場所であると同時に、
   * 自分で登録した品と同梱の品を見分けたり、何が入っているかで探したりする場所でもある。
   *
   * 検索で当たった先（matchReason）を出すのはここだけ（2026-08-20 便IH・②）。
   * 「なぜこの品が出たのか」が分からなくなるのは、**打った言葉で一覧が入れ替わる**この場所だから。
   */
  recipeList: ['time', 'effort', 'season', 'starter', 'ingredients', 'matchReason'],
  /**
   * 献立の枠・買い物メモ・献立テンプレの「レシピを選ぶ」画面
   * （2026-08-19 便IA・オーナー原文「④OKフォーマットそのままで情報減らすなどコンパクトにする
   * 努力はして」）。
   *
   * 便HWでこの画面が料理名だけの行から共通のカードに変わり、1画面に入る品数が
   * 390×844の実測で 6品まで落ちた。**骨格（絵の大きさ・料理名の位置・字の大きさ）は
   * そのままに、載せる情報だけを引く**。
   *
   * 外したもの:
   *  ・基本レシピ … 同梱の品かどうかは「今日この枠で何を作るか」の決め手にならない
   *    （自分で登録した品と見分けたいのはレシピ一覧の側で、そちらには残してある）
   *  ・主要食材 … この画面には検索まどがあり、材料名でも引ける（材料名は検索の索引に
   *    入っている）。3件までのチップより検索のほうが確実に絞れるうえ、
   *    チップの1行ぶんが1画面の品数をいちばん削っていた
   *
   * 残したもの: 調理時間・手間・季節。どれも「今日これを作れるか」を決める材料で、
   * ここを外しても高さは縮まない（同じ1行に並んでいて、絵の高さのほうが高いため）。
   */
  recipePicker: ['time', 'effort', 'season'],
  /**
   * 今日の献立に並ぶ1品も、まだ作る前なので同じだけ載せる
   * （何分かかるか・何を買ってあるかを、この行から読む）。
   */
  todayPlan: ['time', 'effort', 'season', 'starter', 'ingredients'],
  /**
   * 「今日なに作る？」の候補（2026-08-19 便HY・オーナー指示）。
   * **「基本レシピ」と主要食材のチップを出さない**。
   *  ・基本レシピ … ここに出るのは1品か主菜＋副菜の2品だけで、並べて見比べる場所ではない。
   *    同梱かどうかは選ぶ理由にならない（便HWの統一で増えたもので、元は無かった）
   *  ・主要食材 … 押せば開くレシピにそのまま全部書いてある。ここは
   *    「これにするか、引き直すか」を決める場所なので、決め手になる時間・手間・季節を残す
   */
  todaySuggest: ['time', 'effort', 'season'],
  /**
   * 作った記録は、レシピの属性ではなく**その記録の情報**（作った日・何人分・ひとことメモ・
   * 記録に添えた写真）を出す場所なので、レシピ側の情報は載せない。
   * 差し替えは呼び出し側が infoLine / meta で渡す。
   */
  cookedLog: [],
  /**
   * 献立の枠は1行ぶんの高さしか無い（密度「小」）。絵と料理名だけで、
   * ここに並ぶものはもともと1つも無い。
   */
  planSlot: [],
} as const satisfies Record<string, readonly CardPartKey[]>

export type CardPlace = keyof typeof CARD_PLACE_PARTS

/** 省略したときの場所。レシピ一覧＝いちばん情報の多い側に倒す（黙って減らさない） */
export const DEFAULT_CARD_PLACE: CardPlace = 'recipeList'

/** その場所で載せる情報。カード部品はこれを通してからでないと描かない */
export const cardPartsFor = (place: CardPlace = DEFAULT_CARD_PLACE): ReadonlySet<CardPartKey> =>
  new Set(CARD_PLACE_PARTS[place])
